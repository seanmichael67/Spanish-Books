#!/usr/bin/env node
/*
 * Writes ready-to-use marketing material into site/marketing/, using the real
 * books, packs and prices so nothing is out of date:
 *
 *   pinterest-pins.csv      Pinterest bulk upload: one pin per pack, plus the
 *                           library and the free sample (pictures from make-pins.py)
 *   tpt-listings.md         Title, description and tags for each Teachers Pay
 *                           Teachers product
 *   emails/week-1..4.html   Four weekly book-club emails to paste into a Resend Broadcast
 *
 *   node site/scripts/make-marketing.js https://libros.beibeiamigos.com
 */
const fs = require('fs');
const path = require('path');
const { books, packs, library, school, club, config, getTheme, getBook, booksByTheme } = require('../../api/_lib/catalog');

const SITE = (process.argv[2] || 'https://YOUR-NEW-SITE').replace(/\/+$/, '');
const OUT = path.join(__dirname, '..', 'marketing');
const money = (cents) => '$' + (cents % 100 ? (cents / 100).toFixed(2) : cents / 100);
const csv = (v) => `"${String(v).replace(/"/g, '""')}"`;
fs.mkdirSync(path.join(OUT, 'emails'), { recursive: true });

/* ---------- Pinterest ---------- */
const BOARD = 'Spanish Books for Kids';
const rows = [['Title', 'Media URL', 'Pinterest board', 'Thumbnail', 'Description', 'Link', 'Publish date', 'Keywords']];
for (const p of packs) {
  const t = getTheme(p.theme);
  const words = [...new Set(booksByTheme(p.theme).flatMap((b) => b.vocab.map((w) => w.es)))].slice(0, 8);
  rows.push([
    `Spanish books for kids: ${t.en} (${t.es})`,
    `${SITE}/pins/${p.id}.jpg`,
    BOARD,
    '',
    `${p.books.length} free Spanish read-along books about ${t.en.toLowerCase()} for ages 2–6, with real photos and audio on every page. ` +
      `Words like ${words.slice(0, 5).join(', ')}. Printable pack with flashcards and tracing pages.`,
    `${SITE}/temas/${p.theme}/`,
    '',
    `spanish for kids, ${t.en.toLowerCase()} in spanish, bilingual preschool, spanish printables, spanish flashcards`,
  ]);
}
rows.push([`${books.length} free Spanish books for kids with audio`, `${SITE}/pins/library.jpg`, BOARD, '',
  `Free Spanish read-along books for toddlers and preschoolers. Real photos, audio on every page, and the words light up as they are read.`,
  `${SITE}/libros/`, '', 'spanish books for kids, learn spanish preschool, bilingual books, spanish read along']);
rows.push(['Free printable Spanish books for preschool', `${SITE}/pins/free-sample.jpg`, BOARD, '',
  'Two free printable Spanish books with picture vocabulary, cut-out flashcards and tracing pages. Print today.',
  `${SITE}/muestra/`, '', 'free spanish printables, spanish worksheets preschool, spanish flashcards free']);
fs.writeFileSync(path.join(OUT, 'pinterest-pins.csv'), rows.map((r) => r.map(csv).join(',')).join('\n') + '\n');

/* ---------- Teachers Pay Teachers ---------- */
let tpt = `# Teachers Pay Teachers listings

Generated by \`site/scripts/make-marketing.js\`. One section per product. For each one:
upload the PDF made by \`node site/scripts/make-pdfs.js\`, the square cover from
\`site/marketing/tpt/\`, and paste the title, description and tags below.

Suggested settings for every listing: **Grades** PreK, Kindergarten · **Subject** Spanish,
Reading · **Resource type** Printables, Flash Cards, Literacy Center Ideas ·
**Language** Spanish (with English support).

Prices below match the website. TpT takes a fee per sale, so some sellers price a little higher there.

`;
const tptBlock = (title, price, cover, pdf, desc, tags) => `---

## ${title}

- **Price:** ${price}
- **Cover:** \`site/marketing/tpt/${cover}.jpg\`
- **File:** ${pdf === 'biblioteca' ? 'all the PDFs in \`site/marketing/pdfs/\`, zipped into one file' : `\`site/marketing/pdfs/${pdf}.pdf\``}

${desc}

**Tags:** ${tags}

`;
for (const p of packs) {
  const t = getTheme(p.theme);
  const list = booksByTheme(p.theme);
  const words = [...new Set(list.flatMap((b) => b.vocab.map((w) => w.es)))];
  tpt += tptBlock(
    `Spanish Readers for Preschool: ${t.en} (${t.es}) · ${list.length} Printable Books`.slice(0, 80),
    money(p.priceCents),
    p.id,
    p.id,
    `${list.length} simple Spanish readers about ${t.en.toLowerCase()} for ages 2–6, ready to print. Each book has one short sentence and one real photo per page, so new readers can focus on the words.

**Inside:**
- ${list.length} books (cover + 6 story pages each): ${list.map((b) => b.title).join(', ')}
- A picture vocabulary page for every book (${list.length * 6} key words in all)
- Cut-out flashcards for memory games and word hunts
- A trace-and-write page with talk-together questions for every book
- A one-page parent guide, a five-day classroom plan and a reading certificate

**Free audio:** every book can also be read online with a native-sounding Spanish voice at ${SITE}/temas/${p.theme}/, so teachers and families who are still learning Spanish can hear each page.

**Words taught include:** ${words.slice(0, 18).join(', ')}.

Made by ${config.school}, a trilingual Montessori-inspired preschool in Phoenix, Arizona. US Letter, landscape.`,
    `spanish readers, spanish for preschool, ${t.en.toLowerCase()} spanish, spanish vocabulary, bilingual, dual language, spanish flashcards, spanish literacy centers`
  );
}
tpt += tptBlock(
  `Spanish Readers for Preschool: Growing Bundle · ${library.books.length} Printable Books`.slice(0, 80),
  money(library.priceCents),
  'library',
  'biblioteca',
  `Every printable pack in one bundle: ${library.books.length} Spanish readers in ${packs.length} themes, from syllables (ma-me-mi-mo-mu) to short stories, with picture vocabulary, flashcards, tracing pages, parent guides and five-day plans. New packs are added to this growing bundle at no extra cost.

**Themes:** ${packs.map((p) => getTheme(p.theme).en).join(', ')}.

**Free audio** for every book at ${SITE}/libros/.

For a whole school, a site licence is available for ${money(school.priceCents)} at ${SITE}/escuelas/.`,
  'spanish readers bundle, spanish for preschool, spanish kindergarten, dual language, bilingual classroom, spanish flashcards, leveled readers spanish'
);
fs.writeFileSync(path.join(OUT, 'tpt-listings.md'), tpt);

/* ---------- Weekly emails ---------- */
const bookLink = (slug) => {
  const b = getBook(slug);
  return b ? `<a href="${SITE}/libros/${b.slug}/"><strong>${b.title}</strong></a> (${b.titleEn})` : slug;
};
const shell = (preview, body) => `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"></head>
<body style="margin:0;background:#fff9f0;font-family:Verdana,Arial,sans-serif;color:#1f2a44;line-height:1.6">
<span style="display:none">${preview}</span>
<div style="max-width:560px;margin:0 auto;padding:28px 22px">
<p style="font-size:20px;font-weight:bold;margin:0 0 18px">📖 ${config.name}</p>
${body}
<p>Con cariño,<br>${config.school}</p>
<p style="font-size:12px;color:#6b728c;margin-top:30px">You are getting this because you joined the ${config.name} book club.
<a href="{{{RESEND_UNSUBSCRIBE_URL}}}" style="color:#6b728c">Unsubscribe</a></p>
</div></body></html>
`;
const button = (href, label) => `<p style="margin:22px 0"><a href="${href}" style="background:#ff6b4a;color:#fff;padding:12px 22px;border-radius:999px;text-decoration:none;font-weight:bold">${label}</a></p>`;
const emails = [
  ['week-1', 'Start the way Spanish children learn to read', 'Vowels first, then ma-me-mi-mo-mu.', `
<p>¡Hola! In Spanish-speaking classrooms, children learn to read with <strong>syllables</strong>: first the five vowels, then ma-me-mi-mo-mu. Spanish is read almost exactly as it is written, so this works fast.</p>
<p><strong>This week's books:</strong> ${bookLink('silabas-vocales')} and ${bookLink('silabas-m')}.</p>
<p><strong>Try at home (2 minutes):</strong> clap the syllables together. «ma-no» is two claps, «ma-ri-po-sa» is four. Then press 🎤 in the book so your child can say each word after the voice.</p>
${button(`${SITE}/temas/silabas/`, 'Read the syllable books')}
<p>Want them on paper? The <a href="${SITE}/packs/#pack-silabas">Syllables pack</a> has every syllable book with flashcards and tracing pages.</p>`],
  ['week-2', 'A story to read three times', 'Read it Monday, Wednesday and Friday.', `
<p>¡Hola! This week, try a real little story: ${bookLink('cuento-el-gatito-tiene-hambre')}. A hungry kitten looks for food, and a girl helps.</p>
<p><strong>The three-read trick:</strong> read the same story three times this week. The first time, just listen. The second time, press 🎤 <em>Mi turno</em> so your child repeats each sentence. The third time, stop before the last word and let your child finish it.</p>
<p><strong>Ask while you read:</strong> «¿Tiene hambre el gatito?» (Is the kitten hungry?) «¿Qué come?» (What does it eat?)</p>
${button(`${SITE}/libros/cuento-el-gatito-tiene-hambre/`, 'Read El gatito tiene hambre')}
<p>There are ${booksByTheme('cuentos').length} stories in the <a href="${SITE}/temas/cuentos/">Stories collection</a>.</p>`],
  ['week-3', 'A colour hunt in your house', 'Rojo, azul, amarillo, verde.', `
<p>¡Hola! Colours are the easiest words to practise all day long. This week: ${bookLink('el-rojo')}, ${bookLink('el-azul')}, ${bookLink('el-amarillo')} and ${bookLink('el-verde')}.</p>
<p><strong>Colour hunt (5 minutes):</strong> after reading, ask «¿Dónde está algo rojo?» (Where is something red?) and race to find it. Swap roles: your child asks, you find.</p>
<p><strong>Tip:</strong> in the books, tap any word to hear it on its own. Colour words come back in many other books too.</p>
${button(`${SITE}/temas/colores/`, 'Read the colour books')}
<p>The <a href="${SITE}/packs/#pack-colores">Colors &amp; Shapes pack</a> turns all of them into paper books with flashcards.</p>`],
  ['week-4', 'What does the cow say in Spanish?', 'La vaca dice mu.', `
<p>¡Hola! Animal sounds are different in every language, and children love them. In Spanish the cow says «mu», the duck says «cuac» and the sheep says «bee».</p>
<p><strong>This week's books:</strong> ${bookLink('la-vaca')}, ${bookLink('el-pato')} and ${bookLink('la-oveja')}.</p>
<p><strong>Try at home:</strong> you make the sound, your child says the animal in Spanish. Then swap.</p>
${button(`${SITE}/temas/animales/`, 'Read the animal books')}
<p><strong>Printing every week?</strong> The <a href="${SITE}/packs/#club">Club de Lectura</a> is ${money(club.priceCents)} a month for every printable pack, including new ones. Cancel any time.</p>`],
];
for (const [file, subject, preview, body] of emails) {
  fs.writeFileSync(path.join(OUT, 'emails', `${file}.html`), shell(preview, body));
}
fs.writeFileSync(path.join(OUT, 'emails', 'README.md'), `# Weekly book-club emails

Paste each file into a new **Broadcast** in Resend (Broadcasts → Create → HTML), send it to the
book club audience, one a week. \`{{{RESEND_UNSUBSCRIBE_URL}}}\` is filled in by Resend.

| File | Subject line |
|---|---|
${emails.map(([f, s]) => `| \`${f}.html\` | ${s} |`).join('\n')}
`);
console.log(`Wrote pinterest-pins.csv (${rows.length - 1} pins), tpt-listings.md (${packs.length + 1} products) and ${emails.length} emails for ${SITE}`);
